# =========================================================
# FUNÇÃO RECURSIVA
# =========================================================

@auditor
def calcular_orcamento(dados, *departamentos_ignorados, **kwargs):

    total = 0

    # Obtendo taxa de câmbio via kwargs
    taxa_cambio = kwargs.get("taxa_cambio", 1)
    moeda_destino = kwargs.get("moeda_destino", "BRL")

    # Função interna recursiva
    def somar_orcamento(estrutura):

        subtotal = 0

        # Percorre cada item do dicionário
        for chave, valor in estrutura.items():

            # Verifica se o departamento deve ser ignorado
            if chave in departamentos_ignorados:
                print(f"Departamento ignorado: {chave}")
                continue

            # Se for outro dicionário -> chama recursão
            if isinstance(valor, dict):
                subtotal += somar_orcamento(valor)

            # Se for número -> soma ao subtotal
            elif isinstance(valor, (int, float)):
                subtotal += valor

        return subtotal

    # Executa a recursão
    total = somar_orcamento(dados)

    # Aplica taxa de câmbio
    total_convertido = total * taxa_cambio

    print(f"\nMoeda destino: {moeda_destino}")
    print(f"Taxa de câmbio aplicada: {taxa_cambio}")

    return total_convertido


