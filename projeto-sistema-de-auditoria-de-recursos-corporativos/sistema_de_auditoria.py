import time


# =========================================================
# DECORATOR DE AUDITORIA
# =========================================================

def auditor(func):

    def wrapper(*args, **kwargs):

        print("\n" + "=" * 50)
        print("INICIANDO AUDITORIA DO ORÇAMENTO")
        print("=" * 50)

        # Exibe argumentos recebidos
        print(f"Argumentos posicionais (*args): {args[1:]}")
        print(f"Argumentos nomeados (**kwargs): {kwargs}")

        # Marca o tempo inicial
        inicio = time.time()

        # Executa a função original
        resultado = func(*args, **kwargs)

        # Marca o tempo final
        fim = time.time()

        # Calcula duração
        tempo_total = fim - inicio

        print("-" * 50)
        print(f"Tempo de execução: {tempo_total:.6f} segundos")
        print("AUDITORIA FINALIZADA")
        print("=" * 50)

        return resultado

    return wrapper


